from __future__ import annotations

import json
from typing import Any

SYSTEM_PROMPT = """Ты — краткий русскоязычный коуч по силовым тренировкам в зале.
Пиши коротко (5–10 предложений), по делу, без воды и списков из 20 пунктов.
Опирайся ТОЛЬКО на переданные JSON-данные атлета. Не выдумывай веса, даты и симптомы.
Не ставь медицинских диагнозов и не назначай лечение.
Не приказывай менять программу или веса — только наблюдения и мягкие советы.
Если данных мало — скажи об этом прямо.
Не используй HTML/Markdown-разметку.
У каждого атлета свой диалог: учитывай предыдущие реплики в этой беседе, но не чужие данные."""

# Human-readable description of payload fields (shown in Telegram)
DATA_SCHEMA_RU = """В каждый запрос разбора бот добавляет компактный JSON только этого атлета:
• user — фаза, уровень лога, вес тела, стаж
• adherence — сколько тренировок по графику / сколько залогировано
• aggregates — число сессий, суммарный объём, средний RPE, дельта веса
• body_weight_series — последние записи веса
• notes — заметки к упражнениям (укороченные)
• exercise_state — рабочие/предложенные веса, hard_streak, текущая заметка
• sessions — тренировки за окно (14/21/45 дней): дата, шаблон, чекин, подходы или сводка по упражнениям
• focus — session_id / exercise_id / exercise_name для текущего запроса

Чужие атлеты в запрос не попадают. История диалога — только ваши прошлые реплики с коучем."""


def user_prompt_for(
    kind: str,
    athlete_json: str,
    focus: dict[str, Any],
    *,
    locale: str = "ru",
) -> str:
    focus_s = json.dumps(focus or {}, ensure_ascii=False)
    tasks = {
        "session": (
            "Разбери только что законченную тренировку (focus.session_id) "
            "и сравни с предыдущими днями того же шаблона: объём, рабочие веса, "
            "сложность/RPE, чекин (энергия/сон/боль), заметки."
        ),
        "week": (
            "Дай разбор за примерно неделю: посещаемость (adherence), тренд объёма, "
            "вес тела, упражнения с hard_streak, самочувствие по чекинам."
        ),
        "month": (
            "Дай разбор за примерно месяц: прогресс/застой по ключевым упражнениям, "
            "adherence, динамика веса тела, паттерны сложности/RPE."
        ),
        "exercise": (
            "Дай советы по упражнению из focus (exercise_id / exercise_name): "
            "нагрузка, повторы, заметки атлета. Без выдуманной техники «из учебника», "
            "если в данных этого нет."
        ),
    }
    task = tasks.get(kind, tasks["session"])
    return (
        f"Язык ответа: {locale}.\n"
        f"Тип разбора: {kind}.\n"
        f"Задача: {task}\n"
        f"focus={focus_s}\n"
        f"Данные атлета (JSON):\n{athlete_json}"
    )
