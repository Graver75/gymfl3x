"""System / user prompts for the remote Gemini coach."""

from __future__ import annotations

from typing import Any

SYSTEM_PROMPT = """Ты — краткий русскоязычный коуч по силовым тренировкам в зале.
Пиши коротко, по делу, без воды и списков из 20 пунктов.
По цифрам (веса, даты, подходы, чекины) опирайся ТОЛЬКО на JSON атлета — не выдумывай их.
Данные атлета передаются ОДИН раз в блоке JSON. Если поле уже есть в JSON — не жди его
повторной вставки в тексте задачи; смотри по путям (например athlete.live, sessions).
Краткие стандартные cues по технике упражнения по его названию — можно и нужно, когда тип разбора live_set или exercise.
Не ставь медицинских диагнозов и не назначай лечение.
Не приказывай менять программу — только наблюдения и мягкие советы по нагрузке.
Если исторических данных мало — скажи прямо, но технику всё равно опиши кратко.
Не используй HTML/Markdown-разметку.
У каждого атлета свой диалог: учитывай предыдущие реплики в этой беседе (если есть), но не чужие данные.
Для live_set приоритет у актуального JSON, а не у прошлых советов в диалоге."""

DATA_SCHEMA_RU = """В каждый запрос разбора бот добавляет компактный JSON только этого атлета (без дублей):
• user — фаза, уровень лога, вес тела, стаж
• adherence / aggregates / body_weight_series — для week/month/session (в live_set обычно нет)
• notes — заметки к упражнениям (укороченные)
• exercise_state — рабочие/предложенные веса, hard_streak, текущая заметка
• sessions — тренировки за окно
• live — только live_set: текущий подход в зале
• focus — ids/имя цели разбора (без копии полей live)

Чужие атлеты в запрос не попадают."""


def user_prompt_for(
    kind: str,
    athlete_json: str,
    focus: dict[str, Any],
    *,
    locale: str = "ru",
) -> str:
    # focus is already inside athlete JSON; do not paste it again
    _ = focus
    tasks = {
        "session": (
            "Только что закончена тренировка athlete.focus.session_id. "
            "В ОДНОМ ответе разбери КАЖДОЕ упражнение этой сессии: "
            "сравни подходы/веса/сложность с 1–2 предыдущими днями того же шаблона "
            "(если есть в JSON). Плюс кратко: общий объём, чекин, заметки. "
            "Структура: по упражнениям по пунктам, без воды. "
            "Не больше ~12–15 коротких предложений суммарно."
        ),
        "week": (
            "Дай разбор за примерно неделю: посещаемость (adherence), тренд объёма, "
            "вес тела, упражнения с hard_streak, самочувствие по чекинам."
        ),
        "month": (
            "Дай разбор за примерно месяц: прогресс/застой по ключевым упражнениям, "
            "adherence, динамика веса тела, паттерны сложности/RPE."
        ),
        "exercise": (
            "Структура ответа строго: (1) краткое описание техники упражнения "
            "из athlete.focus.exercise_name — 3–5 ключевых точек; "
            "(2) summary по JSON: история подходов, веса, заметки, exercise_state. "
            "Не выдумывай цифры, которых нет в данных."
        ),
        "live_set": (
            "Атлет СЕЙЧАС в зале. Смотри ТОЛЬКО JSON: athlete.live (текущий подход), "
            "sessions / exercise_state / notes по этому упражнению. "
            "Структура ответа строго: (1) краткая техника по athlete.live.exercise_name "
            "(3–5 cues); (2) summary по уже сделанному сегодня + истории; "
            "мягкий совет на текущий подход. "
            "Не больше 6–8 предложений. Не выдумывай цифры вне JSON."
        ),
    }
    task = tasks.get(kind, tasks["session"])
    return (
        f"Язык ответа: {locale}.\n"
        f"Тип разбора: {kind}.\n"
        f"Задача: {task}\n"
        f"Данные атлета (JSON, один раз):\n{athlete_json}"
    )
